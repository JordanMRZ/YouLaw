function createLessons(level, titles) {
  return titles.map((lesson, index) => ({
    id: `${level}-${index + 1}`,
    level,
    number: String(index + 1).padStart(2, '0'),
    title: lesson.title,
    subtitle: lesson.subtitle,
    state: index === 0 ? 'current' : 'locked',
    color: ['coral', 'blue', 'yellow', 'mint'][index % 4],
  }))
}

